/**
 * Builds a greeting for a person.
 * @param {string} name Name of the person to greet.
 */
export function greet(name) {
  return `Hello, ${name}!`;
}

/**
 * Builds a greeting in French.
 * @param {string} name Name of the person to greet.
 */
export function greetInFrench(name) {
  return `Bonjour, ${name} !`;
}
